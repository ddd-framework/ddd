<?php

declare(strict_types=1);

namespace DDD\Testing\MediaItems;

use UnexpectedValueException;

/**
 * Builds, byte for byte and without any production class, the metadata marks the image tests inject into fixtures:
 * an EXIF TIFF block (Make and Orientation only: ImageMagick rewrites the resolution tags 0x011A, 0x011B and 0x0128 on
 * a re-encode, so the fixtures never carry them), an XMP packet declaring the IPTC digital source type
 * `trainedAlgorithmicMedia` plus a field an AI tag never writes, a Photoshop APP13 payload holding IPTC IIM, a
 * C2PA-style JUMBF box, and the JPEG segments and PNG chunks that carry them.
 */
class ImageMarkFixtureBuilder
{
    /** @var string The identifier an Exif APP1 payload starts with */
    public const string EXIF_IDENTIFIER = "Exif\0\0";

    /** @var string The identifier the main XMP APP1 payload starts with */
    public const string XMP_IDENTIFIER = "http://ns.adobe.com/xap/1.0/\0";

    /** @var string The identifier every extended XMP APP1 payload starts with */
    public const string EXTENDED_XMP_IDENTIFIER = "http://ns.adobe.com/xmp/extension/\0";

    /** @var string The identifier an APP13 payload holding Photoshop image resources (IPTC IIM) starts with */
    public const string PHOTOSHOP_IDENTIFIER = "Photoshop 3.0\0";

    /** @var string The keyword of the PNG text chunk carrying XMP */
    public const string XMP_PNG_KEYWORD = 'XML:com.adobe.xmp';

    /** @var string The IPTC digital source type of an image generated by a trained model */
    public const string DIGITAL_SOURCE_TYPE_TRAINED_ALGORITHMIC_MEDIA = 'http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia';

    /** @var int JPEG marker APP0 */
    public const int MARKER_APP0 = 0xE0;

    /** @var int JPEG marker APP1 (Exif, XMP) */
    public const int MARKER_APP1 = 0xE1;

    /** @var int JPEG marker APP11 (JUMBF / C2PA) */
    public const int MARKER_APP11 = 0xEB;

    /** @var int JPEG marker APP13 (Photoshop image resources, IPTC IIM) */
    public const int MARKER_APP13 = 0xED;

    /** @var int JPEG marker COM */
    public const int MARKER_COMMENT = 0xFE;

    /** @var int The most payload bytes one JPEG segment can carry: the 16-bit length field counts itself */
    public const int MAX_JPEG_SEGMENT_PAYLOAD_LENGTH = 65533;

    /** @var string The Make value of the fixture EXIF */
    public const string EXIF_MAKE = 'RC fixture camera';

    /**
     * A little-endian TIFF block with IFD0 holding Make and Orientation ($orientation, 1 unless given); with a
     * thumbnail, IFD1 points at it through JPEGInterchangeFormat / JPEGInterchangeFormatLength, so the block carries
     * the thumbnail's own `FFD8 ... FFD9`.
     */
    public static function buildExifTiffBlock(?string $thumbnailJpegBytes = null, int $orientation = 1): string
    {
        $makeValue = self::EXIF_MAKE . "\0";
        $ifd0Offset = 8;
        $ifd0Length = 2 + 2 * 12 + 4;
        $makeValueOffset = $ifd0Offset + $ifd0Length;
        $ifd1Offset = $makeValueOffset + strlen($makeValue) + (strlen($makeValue) % 2);
        $nextIfdOffset = $thumbnailJpegBytes === null ? 0 : $ifd1Offset;

        $tiffBlock = "II\x2A\x00" . pack('V', $ifd0Offset)
            . pack('v', 2)
            . pack('vvVV', 0x010F, 2, strlen($makeValue), $makeValueOffset)
            . pack('vvV', 0x0112, 3, 1) . pack('v', $orientation) . "\0\0"
            . pack('V', $nextIfdOffset)
            . $makeValue . str_repeat("\0", strlen($makeValue) % 2);
        if ($thumbnailJpegBytes === null) {
            return $tiffBlock;
        }
        $ifd1Length = 2 + 2 * 12 + 4;
        $thumbnailOffset = $ifd1Offset + $ifd1Length;
        return $tiffBlock
            . pack('v', 2)
            . pack('vvVV', 0x0201, 4, 1, $thumbnailOffset)
            . pack('vvVV', 0x0202, 4, 1, strlen($thumbnailJpegBytes))
            . pack('V', 0)
            . $thumbnailJpegBytes;
    }

    /**
     * A TIFF block of exactly $byteLength bytes: the fixture block followed by unreferenced filler bytes.
     */
    public static function buildExifTiffBlockOfLength(int $byteLength): string
    {
        $tiffBlock = self::buildExifTiffBlock();
        if ($byteLength < strlen($tiffBlock)) {
            throw new UnexpectedValueException("A TIFF block needs at least " . strlen($tiffBlock) . " bytes");
        }
        return $tiffBlock . str_repeat("\0", $byteLength - strlen($tiffBlock));
    }

    /**
     * An XMP packet declaring Iptc4xmpExt:DigitalSourceType = trainedAlgorithmicMedia and a `photoshop:Credit` field
     * that an AI tag never writes, so a test can tell the input's XMP from that tag; with $byteLength,
     * whitespace padding (allowed before the packet trailer) makes it exactly that long.
     */
    public static function buildXmpPacket(?int $byteLength = null): string
    {
        $packetWithoutTrailer = '<?xpacket begin="' . "\u{FEFF}" . '" id="W5M0MpCehiHzreSzNTczkc9d"?>'
            . '<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
            . '<rdf:Description rdf:about="" xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/"'
            . ' xmlns:photoshop="http://ns.adobe.com/photoshop/1.0/"'
            . ' Iptc4xmpExt:DigitalSourceType="' . self::DIGITAL_SOURCE_TYPE_TRAINED_ALGORITHMIC_MEDIA . '"'
            . ' photoshop:Credit="RC fixture"/>'
            . '</rdf:RDF></x:xmpmeta>';
        $packetTrailer = '<?xpacket end="w"?>';
        if ($byteLength === null) {
            return $packetWithoutTrailer . $packetTrailer;
        }
        $paddingLength = $byteLength - strlen($packetWithoutTrailer) - strlen($packetTrailer);
        if ($paddingLength < 0) {
            throw new UnexpectedValueException('An XMP packet needs at least ' . ($byteLength - $paddingLength) . ' bytes');
        }
        return $packetWithoutTrailer . str_repeat(' ', $paddingLength) . $packetTrailer;
    }

    /**
     * The payload of an APP13 segment: the Photoshop identifier and one 8BIM image resource 0x0404 (IPTC-NAA) holding
     * an IIM record version and a caption.
     */
    public static function buildIptcPhotoshopPayload(string $caption = 'RC fixture caption'): string
    {
        $iptcRecords = "\x1C\x02\x00" . pack('n', 2) . "\x00\x04"
            . "\x1C\x02\x78" . pack('n', strlen($caption)) . $caption;
        $imageResource = '8BIM' . pack('n', 0x0404) . "\0\0" . pack('N', strlen($iptcRecords))
            . $iptcRecords . str_repeat("\0", strlen($iptcRecords) % 2);
        return self::PHOTOSHOP_IDENTIFIER . $imageResource;
    }

    /**
     * A C2PA-style JUMBF superbox (`jumb` holding a `jumd` description box labelled `c2pa`).
     */
    public static function buildJumbfBox(): string
    {
        $descriptionBoxContent = 'c2pa' . "\x00\x11\x00\x10\x80\x00\x00\xAA\x00\x38\x9B\x71" . "\x03" . "c2pa\0";
        $descriptionBox = pack('N', 8 + strlen($descriptionBoxContent)) . 'jumd' . $descriptionBoxContent;
        return pack('N', 8 + strlen($descriptionBox)) . 'jumb' . $descriptionBox;
    }

    /** The payload of an APP11 segment carrying the JUMBF box: common identifier `JP`, box instance, sequence. */
    public static function buildJumbfApp11Payload(): string
    {
        return 'JP' . pack('n', 1) . pack('N', 1) . self::buildJumbfBox();
    }

    /** The Exif APP1 payload of the fixtures, with Orientation $orientation (1 unless given). */
    public static function buildExifApp1Payload(?string $thumbnailJpegBytes = null, int $orientation = 1): string
    {
        return self::EXIF_IDENTIFIER . self::buildExifTiffBlock($thumbnailJpegBytes, $orientation);
    }

    /** The main XMP APP1 payload of the fixtures. */
    public static function buildXmpApp1Payload(?string $xmpPacket = null): string
    {
        return self::XMP_IDENTIFIER . ($xmpPacket ?? self::buildXmpPacket());
    }

    /** An extended XMP APP1 payload: identifier, 32-byte GUID, full length, offset, then a part of the packet. */
    public static function buildExtendedXmpApp1Payload(string $packetPart, int $partOffset = 0): string
    {
        return self::EXTENDED_XMP_IDENTIFIER . str_repeat('A', 32) . pack('N', 4096) . pack('N', $partOffset) . $packetPart;
    }

    /**
     * One JPEG marker segment: `FF`, the marker, the 16-bit length (which counts itself) and the payload.
     */
    public static function buildJpegSegment(int $marker, string $payload): string
    {
        if (strlen($payload) > self::MAX_JPEG_SEGMENT_PAYLOAD_LENGTH) {
            throw new UnexpectedValueException('A JPEG segment holds at most 65,533 payload bytes');
        }
        return "\xFF" . chr($marker) . pack('n', strlen($payload) + 2) . $payload;
    }

    /** The four fixture marks as JPEG segments, in the order Exif APP1, XMP APP1, APP13, APP11. */
    public static function buildAllFourJpegMarkSegments(): string
    {
        return self::buildJpegSegment(self::MARKER_APP1, self::buildExifApp1Payload())
            . self::buildJpegSegment(self::MARKER_APP1, self::buildXmpApp1Payload())
            . self::buildJpegSegment(self::MARKER_APP13, self::buildIptcPhotoshopPayload())
            . self::buildJpegSegment(self::MARKER_APP11, self::buildJumbfApp11Payload());
    }

    /**
     * Inserts already built segments directly after the target's APP0 segment, or directly after SOI when the first
     * segment is not APP0.
     */
    public static function insertIntoJpegAfterApp0OrSoi(string $jpegBytes, string $segmentsBytes): string
    {
        $firstSegment = ImageStructureWalker::listJpegSegmentsUpToFirstScan($jpegBytes)[0];
        $insertionOffset = $firstSegment['kind'] === ImageStructureWalker::JPEG_KIND_APP0
            ? $firstSegment['offset'] + $firstSegment['length']
            : 2;
        return substr($jpegBytes, 0, $insertionOffset) . $segmentsBytes . substr($jpegBytes, $insertionOffset);
    }

    /**
     * COM segments directly after SOI that make the JPEG exactly $targetByteLength bytes long.
     *
     * @throws UnexpectedValueException When the gap is 1 to 3 bytes (no segment is that short) or negative.
     */
    public static function padJpegWithCommentSegmentsToLength(string $jpegBytes, int $targetByteLength): string
    {
        $gapLength = $targetByteLength - strlen($jpegBytes);
        if ($gapLength < 0 || ($gapLength > 0 && $gapLength < 4)) {
            throw new UnexpectedValueException("Cannot pad a JPEG of " . strlen($jpegBytes) . " bytes to {$targetByteLength} bytes");
        }
        $segmentCount = (int)ceil($gapLength / (self::MAX_JPEG_SEGMENT_PAYLOAD_LENGTH + 4));
        return substr($jpegBytes, 0, 2)
            . self::buildCommentSegmentsWithPayloadLength($gapLength - 4 * $segmentCount)
            . substr($jpegBytes, 2);
    }

    /**
     * As many COM segments as needed (each full but the last) to carry $totalPayloadLength comment bytes.
     */
    public static function buildCommentSegmentsWithPayloadLength(int $totalPayloadLength): string
    {
        $commentSegments = '';
        while ($totalPayloadLength > 0) {
            $segmentPayloadLength = min($totalPayloadLength, self::MAX_JPEG_SEGMENT_PAYLOAD_LENGTH);
            $commentSegments .= self::buildJpegSegment(self::MARKER_COMMENT, str_repeat('c', $segmentPayloadLength));
            $totalPayloadLength -= $segmentPayloadLength;
        }
        return $commentSegments;
    }

    /** One PNG chunk with its CRC over type and data. */
    public static function buildPngChunk(string $chunkType, string $chunkData): string
    {
        return pack('N', strlen($chunkData)) . $chunkType . $chunkData . pack('N', crc32($chunkType . $chunkData));
    }

    /**
     * An XMP text chunk with keyword `XML:com.adobe.xmp`, laid out as the PNG specification describes: `iTXt`
     * (uncompressed or zlib-compressed), `zTXt` (always zlib-compressed) or `tEXt`.
     */
    public static function buildPngXmpChunk(string $xmpPacket, string $chunkType = 'iTXt', bool $isCompressed = false): string
    {
        $keywordField = self::XMP_PNG_KEYWORD . "\0";
        return match ($chunkType) {
            'iTXt' => self::buildPngChunk(
                'iTXt',
                $keywordField . ($isCompressed ? "\x01" : "\x00") . "\x00" . "\0" . "\0"
                . ($isCompressed ? gzcompress($xmpPacket) : $xmpPacket),
            ),
            'zTXt' => self::buildPngChunk('zTXt', $keywordField . "\x00" . gzcompress($xmpPacket)),
            'tEXt' => self::buildPngChunk('tEXt', $keywordField . $xmpPacket),
            default => throw new UnexpectedValueException("{$chunkType} is not a PNG text chunk type"),
        };
    }

    /** A compressed XMP `iTXt` chunk (valid CRC) whose text is not a zlib stream. */
    public static function buildPngXmpITxtChunkWithCorruptZlibStream(): string
    {
        return self::buildPngChunk(
            'iTXt',
            self::XMP_PNG_KEYWORD . "\0" . "\x01" . "\x00" . "\0" . "\0" . 'this is not a zlib stream',
        );
    }

    /** The fixture marks a PNG can carry, as chunks: `eXIf`, uncompressed XMP `iTXt`, `caBX`. */
    public static function buildExifXmpAndCaBxPngChunks(): string
    {
        return self::buildPngChunk('eXIf', self::buildExifTiffBlock())
            . self::buildPngXmpChunk(self::buildXmpPacket())
            . self::buildPngChunk('caBX', self::buildJumbfBox());
    }

    /**
     * Inserts already built chunks directly after IHDR (the first chunk).
     */
    public static function insertIntoPngAfterIhdr(string $pngBytes, string $chunksBytes): string
    {
        $ihdrChunk = ImageStructureWalker::listPngChunks($pngBytes)[0];
        if ($ihdrChunk['type'] !== 'IHDR') {
            throw new UnexpectedValueException('The first PNG chunk is not IHDR');
        }
        $insertionOffset = $ihdrChunk['offset'] + $ihdrChunk['length'];
        return substr($pngBytes, 0, $insertionOffset) . $chunksBytes . substr($pngBytes, $insertionOffset);
    }

    /**
     * Inserts already built chunks directly before IEND.
     */
    public static function insertIntoPngBeforeIend(string $pngBytes, string $chunksBytes): string
    {
        $iendChunk = ImageStructureWalker::listPngChunksOfType($pngBytes, 'IEND')[0];
        return substr($pngBytes, 0, $iendChunk['offset']) . $chunksBytes . substr($pngBytes, $iendChunk['offset']);
    }
}
