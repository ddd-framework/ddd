<?php

declare(strict_types=1);

namespace DDD\Tools\SkillLinks;

use JsonException;
use RuntimeException;
use Throwable;

/**
 * Links the agent skills shipped by DDD packages (`<package>/.claude/skills/<name>/SKILL.md` of every
 * `vendor/mgamadeus/*` and `node_modules/@mgamadeus/*` below the repository root) into the repository's
 * `.claude/skills`, mirrors them into existing Codex folders (`.agents/skills`, `.codex/skills`), removes links whose
 * skill is gone, records what it wrote in `.ddd-skills.json` and keeps the generated names in a managed `.gitignore`
 * block.
 *
 * Plain PHP on purpose: it runs from Composer's post-install-cmd / post-update-cmd without booting a kernel and
 * without loading the application's autoloader. The npm package `@mgamadeus/ddd-web` (`ddd-web link-skills`)
 * implements the same behaviour and reads and writes the same manifest, so both install hooks agree.
 */
class VendorSkillLinker
{
    public const string PRIMARY_SKILLS_DIRECTORY = '.claude/skills';

    /** Codex skill folders, mirrored only when they already exist */
    public const array MIRROR_SKILLS_DIRECTORIES = ['.agents/skills', '.codex/skills'];

    public const string MANIFEST_FILE_NAME = '.ddd-skills.json';

    public const int MANIFEST_FORMAT = 1;

    public const string GITIGNORE_FILE_NAME = '.gitignore';

    public const string GITIGNORE_BLOCK_START = '# ddd-skills:start';

    public const string GITIGNORE_BLOCK_END = '# ddd-skills:end';

    public const string GITIGNORE_BLOCK_COMMENT = '# Generated by ddd-link-skills / ddd-web link-skills; rewritten on every install.';

    /** Deepest level below the root at which a `vendor/` or `node_modules/` folder is searched (`apps/admin/vendor`) */
    public const int MAXIMUM_INSTALL_FOLDER_DEPTH = 3;

    public const string ROOT_ENVIRONMENT_VARIABLE = 'DDD_SKILLS_ROOT';

    public const string OUTPUT_PREFIX = '[ddd-skills] ';

    public const int EXIT_SUCCESS = 0;

    public const int EXIT_FAILURE = 1;

    public const string ENTRY_MISSING = 'missing';

    public const string ENTRY_LINK = 'link';

    public const string ENTRY_DIRECTORY = 'directory';

    public const string ENTRY_FILE = 'file';

    public const string OPERATION_LINK = 'link';

    public const string OPERATION_RELINK = 'relink';

    public const string OPERATION_REMOVE = 'remove';

    public const string OPERATION_WRITE = 'write';

    /** Labels per operation: [applied, dry run, check] */
    public const array OPERATION_LABELS = [
        self::OPERATION_LINK => ['linked', 'would link', 'missing'],
        self::OPERATION_RELINK => ['relinked', 'would relink', 'stale'],
        self::OPERATION_REMOVE => ['removed', 'would remove', 'broken'],
        self::OPERATION_WRITE => ['updated', 'would update', 'outdated'],
    ];

    public const string USAGE = <<<'TEXT'
Usage: ddd-link-skills [--check] [--dry-run] [--quiet] [--root <dir>]

Links the agent skills of every vendor/mgamadeus/* and node_modules/@mgamadeus/* package below the repository root
into .claude/skills (and into existing .agents/skills, .codex/skills folders).

  --check        change nothing; exit 1 when links are missing, stale or broken, on clashes, on generated links
                 still tracked by git and on edited vendor skills
  --dry-run      print what would change, change nothing
  --quiet        print only warnings and problems
  --root <dir>   repository root (default: nearest ancestor with .git, else with .claude; env DDD_SKILLS_ROOT)
  -h, --help     show this help

TEXT;

    /** Real path of the repository root */
    protected string $rootDirectory;

    protected bool $checkOnly;

    protected bool $dryRun;

    protected bool $quiet;

    /** @var resource|null */
    protected $outputStream;

    /** @var resource|null */
    protected $errorStream;

    /** @var string[] every line printed, in order (without prefix) */
    protected array $printedLines = [];

    /** @var string[] check problems and warnings of the last run */
    protected array $problems = [];

    /**
     * @param string $rootDirectory Repository root (see findRepositoryRoot())
     * @param bool $checkOnly Change nothing, report every deviation, exit 1 on any
     * @param bool $dryRun Change nothing, print what would change
     * @param bool $quiet Print only warnings and problems
     * @param resource|null $outputStream Stream for change lines (default STDOUT; null prints nothing)
     * @param resource|null $errorStream Stream for warnings and problems (default STDERR; null prints nothing)
     */
    public function __construct(
        string $rootDirectory,
        bool $checkOnly = false,
        bool $dryRun = false,
        bool $quiet = false,
        mixed $outputStream = STDOUT,
        mixed $errorStream = STDERR
    ) {
        $realRootDirectory = realpath($rootDirectory);
        if ($realRootDirectory === false || !is_dir($realRootDirectory)) {
            throw new RuntimeException("The root directory {$rootDirectory} does not exist");
        }
        $this->rootDirectory = $realRootDirectory;
        $this->checkOnly = $checkOnly;
        $this->dryRun = $dryRun;
        $this->quiet = $quiet;
        $this->outputStream = $outputStream;
        $this->errorStream = $errorStream;
    }

    /**
     * Entry point of the bin script.
     *
     * @param string[] $arguments Command line arguments without the script name
     * @param string $currentDirectory Directory the search for the repository root starts from
     * @return int Exit code
     */
    public static function runFromCommandLine(array $arguments, string $currentDirectory): int
    {
        $checkOnly = false;
        $dryRun = false;
        $quiet = false;
        $rootDirectory = null;
        for ($index = 0; $index < count($arguments); $index++) {
            $argument = $arguments[$index];
            if ($argument === '--check') {
                $checkOnly = true;
            } elseif ($argument === '--dry-run') {
                $dryRun = true;
            } elseif ($argument === '--quiet' || $argument === '-q') {
                $quiet = true;
            } elseif ($argument === '--root' && isset($arguments[$index + 1])) {
                $rootDirectory = $arguments[++$index];
            } elseif (str_starts_with($argument, '--root=')) {
                $rootDirectory = substr($argument, strlen('--root='));
            } elseif ($argument === '--help' || $argument === '-h') {
                fwrite(STDOUT, self::USAGE);
                return self::EXIT_SUCCESS;
            } else {
                fwrite(STDERR, self::OUTPUT_PREFIX . "unknown option {$argument}\n" . self::USAGE);
                return self::EXIT_FAILURE;
            }
        }
        if ($rootDirectory === null) {
            $environmentRoot = getenv(self::ROOT_ENVIRONMENT_VARIABLE);
            $rootDirectory = is_string($environmentRoot) && $environmentRoot !== ''
                ? $environmentRoot
                : static::findRepositoryRoot($currentDirectory);
        } elseif (!str_starts_with($rootDirectory, '/')) {
            $rootDirectory = $currentDirectory . '/' . $rootDirectory;
        }
        try {
            $vendorSkillLinker = new static($rootDirectory, $checkOnly, $dryRun, $quiet);
        } catch (Throwable $throwable) {
            fwrite(STDERR, self::OUTPUT_PREFIX . 'error: ' . $throwable->getMessage() . "\n");
            return self::EXIT_FAILURE;
        }
        return $vendorSkillLinker->run();
    }

    /**
     * The repository root: the nearest ancestor of $startDirectory (itself included) that contains `.git` (folder or
     * file), else the nearest that contains `.claude` (the home folder's `.claude` is the user's global configuration
     * and never counts), else $startDirectory itself.
     */
    public static function findRepositoryRoot(string $startDirectory): string
    {
        $startDirectory = realpath($startDirectory) ?: $startDirectory;
        foreach (['.git', '.claude'] as $marker) {
            $homeDirectory = getenv('HOME') ?: null;
            $realHomeDirectory = $homeDirectory !== null ? (realpath($homeDirectory) ?: $homeDirectory) : null;
            $directory = $startDirectory;
            while (true) {
                $markerPath = $directory . '/' . $marker;
                $isHomeClaude = $marker === '.claude' && $directory === $realHomeDirectory;
                if (!$isHomeClaude && (file_exists($markerPath) || is_link($markerPath))) {
                    return $directory;
                }
                $parentDirectory = dirname($directory);
                if ($parentDirectory === $directory) {
                    break;
                }
                $directory = $parentDirectory;
            }
        }
        return $startDirectory;
    }

    public function getRootDirectory(): string
    {
        return $this->rootDirectory;
    }

    /**
     * @return string[] Lines printed by the last run, without prefix
     */
    public function getPrintedLines(): array
    {
        return $this->printedLines;
    }

    /**
     * @return string[] Problems (check mode) and warnings of the last run, without prefix
     */
    public function getProblems(): array
    {
        return $this->problems;
    }

    /**
     * Plans and (unless --check / --dry-run) applies the links, the manifest and the gitignore blocks.
     *
     * @return int 0, or 1 on check problems and on unexpected errors while writing
     */
    public function run(): int
    {
        $this->printedLines = [];
        $this->problems = [];
        try {
            $plan = $this->createPlan();
        } catch (Throwable $throwable) {
            $this->printWarning('error: ' . $throwable->getMessage());
            return self::EXIT_FAILURE;
        }
        if ($plan['nothingToDo']) {
            $this->printInfo('no DDD package ships agent skills below ' . $this->rootDirectory . '; nothing to link');
            return self::EXIT_SUCCESS;
        }
        $modeIndex = $this->checkOnly ? 2 : ($this->dryRun ? 1 : 0);
        foreach ($plan['warnings'] as $warning) {
            $this->problems[] = $warning;
        }
        if (!$this->checkOnly && !$this->dryRun) {
            try {
                $this->applyOperations($plan['operations']);
            } catch (Throwable $throwable) {
                $this->printWarning('error: ' . $throwable->getMessage());
                return self::EXIT_FAILURE;
            }
        }
        foreach ($plan['operations'] as $operation) {
            $line = $this->formatLabel(self::OPERATION_LABELS[$operation['kind']][$modeIndex]) . $operation['display'];
            if ($this->checkOnly) {
                $this->problems[] = $line;
                $this->printWarning($line);
            } else {
                $this->printChange($line);
            }
        }
        foreach ($plan['warnings'] as $warning) {
            $this->printWarning($warning);
        }
        $skillCount = count($plan['managedSkillNames']);
        $packageCount = count($plan['packageNames']);
        $changeCount = count($plan['operations']);
        if ($this->checkOnly) {
            $problemCount = count($this->problems);
            if ($problemCount > 0) {
                $this->printWarning(
                    "check failed: {$problemCount} problem(s); run ddd-link-skills (or ddd-web link-skills) to fix the links"
                );
                return self::EXIT_FAILURE;
            }
            $this->printInfo("check passed: {$skillCount} skill(s) from {$packageCount} package(s)");
            return self::EXIT_SUCCESS;
        }
        if ($this->dryRun) {
            $this->printInfo("dry run: {$changeCount} change(s) would be made");
            return self::EXIT_SUCCESS;
        }
        $this->printInfo("{$skillCount} skill(s) from {$packageCount} package(s), {$changeCount} change(s)");
        return self::EXIT_SUCCESS;
    }

    /**
     * Computes every operation and warning without changing anything.
     *
     * Plan keys: nothingToDo (bool), operations (list of operation arrays), warnings (string[]),
     * managedSkillNames (string[]), packageNames (string[]).
     */
    protected function createPlan(): array
    {
        clearstatcache(true);
        $operations = [];
        $warnings = [];
        $discovery = $this->discoverSkills();
        $warnings = [...$warnings, ...$discovery['warnings']];
        $winnersByName = $discovery['winners'];

        $primaryLogicalDirectory = $this->rootDirectory . '/' . self::PRIMARY_SKILLS_DIRECTORY;
        $primaryDirectory = $this->resolvePrimaryDirectory();
        $primaryExists = is_dir($primaryLogicalDirectory);
        if (!$primaryExists && count($winnersByName) === 0) {
            return ['nothingToDo' => true, 'operations' => [], 'warnings' => [], 'managedSkillNames' => [], 'packageNames' => []];
        }
        if (!$primaryExists) {
            $operations[] = ['kind' => 'mkdir', 'path' => $primaryDirectory, 'display' => ''];
        }
        $previousManifestPath = $primaryDirectory . '/' . self::MANIFEST_FILE_NAME;
        $previousManifestEntries = $this->readManifestEntries($previousManifestPath);
        if ($previousManifestEntries === null) {
            $warnings[] = $this->formatLabel('manifest') . $this->getDisplayPath($previousManifestPath) . ' is not readable; rewritten';
            $previousManifestEntries = [];
        }

        // Primary entries of the discovered skills
        $managedEntries = [];
        foreach ($winnersByName as $skillName => $skill) {
            $linkPath = $primaryDirectory . '/' . $skillName;
            $desiredTarget = $this->getRelativePath($primaryDirectory, $skill['directory']);
            $display = self::PRIMARY_SKILLS_DIRECTORY . '/' . $skillName;
            $entryType = $this->getEntryType($linkPath);
            if ($entryType === self::ENTRY_MISSING) {
                $operations[] = ['kind' => self::OPERATION_LINK, 'path' => $linkPath, 'target' => $desiredTarget, 'display' => "{$display} -> {$desiredTarget}"];
            } elseif ($entryType === self::ENTRY_LINK) {
                $currentTarget = (string)readlink($linkPath);
                if ($currentTarget !== $desiredTarget) {
                    if (!$this->isDddVendorPath($this->resolveLinkTarget($primaryDirectory, $currentTarget))) {
                        $warnings[] = $this->formatLabel('clash') . "{$display}: a symlink of the app to {$currentTarget} exists; the skill of {$skill['package']} is not linked";
                        continue;
                    }
                    $operations[] = ['kind' => self::OPERATION_RELINK, 'path' => $linkPath, 'target' => $desiredTarget, 'display' => "{$display} -> {$desiredTarget} (was {$currentTarget})"];
                }
            } else {
                $warnings[] = $this->formatLabel('clash') . "{$display}: the app has its own skill of this name; the skill of {$skill['package']} is not linked";
                continue;
            }
            $skillFileHash = (string)hash_file('sha256', $skill['directory'] . '/SKILL.md');
            $previousEntry = $previousManifestEntries[$skillName] ?? null;
            if (
                is_array($previousEntry) && ($previousEntry['package'] ?? null) === $skill['package']
                && ($previousEntry['version'] ?? null) === $skill['version'] && $skill['version'] !== null
                && is_string($previousEntry['sha256'] ?? null) && $previousEntry['sha256'] !== $skillFileHash
            ) {
                $warnings[] = $this->formatLabel('edited') . "{$skillName}: SKILL.md of {$skill['package']} {$skill['version']} differs from the installed copy recorded in the manifest";
                $skillFileHash = $previousEntry['sha256'];
            }
            $managedEntries[$skillName] = [
                'package' => $skill['package'],
                'version' => $skill['version'],
                'source' => $this->getRelativePath($this->rootDirectory, $skill['directory']),
                'target' => $desiredTarget,
                'sha256' => $skillFileHash,
                'mirrors' => [],
            ];
        }

        // Former entries: keep those still resolving (another install tree), remove broken DDD links
        $removedSkillNames = [];
        foreach ($previousManifestEntries as $skillName => $previousEntry) {
            if (isset($managedEntries[$skillName]) || isset($winnersByName[$skillName]) || !is_array($previousEntry)) {
                continue;
            }
            $linkPath = $primaryDirectory . '/' . $skillName;
            if ($this->getEntryType($linkPath) !== self::ENTRY_LINK) {
                continue;
            }
            $currentTarget = (string)readlink($linkPath);
            $resolvedTarget = $this->resolveLinkTarget($primaryDirectory, $currentTarget);
            if (!$this->isDddVendorPath($resolvedTarget)) {
                continue;
            }
            if (file_exists($linkPath)) {
                $managedEntries[$skillName] = [
                    'package' => $previousEntry['package'] ?? null,
                    'version' => $previousEntry['version'] ?? null,
                    'source' => $previousEntry['source'] ?? null,
                    'target' => $currentTarget,
                    'sha256' => $previousEntry['sha256'] ?? null,
                    'mirrors' => [],
                ];
            }
        }
        // Broken links into a DDD vendor area (skill no longer shipped, package removed)
        foreach ($this->listDirectoryNames($primaryDirectory) as $entryName) {
            $linkPath = $primaryDirectory . '/' . $entryName;
            if (isset($managedEntries[$entryName]) || $this->getEntryType($linkPath) !== self::ENTRY_LINK || file_exists($linkPath)) {
                continue;
            }
            $currentTarget = (string)readlink($linkPath);
            if ($this->isDddVendorPath($this->resolveLinkTarget($primaryDirectory, $currentTarget))) {
                $removedSkillNames[$entryName] = true;
                $operations[] = ['kind' => self::OPERATION_REMOVE, 'path' => $linkPath, 'display' => self::PRIMARY_SKILLS_DIRECTORY . "/{$entryName} (broken link to {$currentTarget})"];
            }
        }
        ksort($managedEntries, SORT_STRING);

        // Mirrors
        $mirrorGitignoreNames = [];
        $gitPaths = [];
        foreach (self::MIRROR_SKILLS_DIRECTORIES as $mirrorName) {
            $mirrorLogicalDirectory = $this->rootDirectory . '/' . $mirrorName;
            if ($this->getEntryType($mirrorLogicalDirectory) === self::ENTRY_MISSING || !is_dir($mirrorLogicalDirectory)) {
                continue;
            }
            $mirrorDirectory = (string)realpath($mirrorLogicalDirectory);
            $mirrorParentDirectory = (string)realpath(dirname($mirrorLogicalDirectory));
            if ($mirrorDirectory === $primaryDirectory || $mirrorParentDirectory === $primaryDirectory) {
                continue;
            }
            $mirrorGitignoreNames[$mirrorDirectory] = [];
            foreach (array_keys($managedEntries) as $skillName) {
                $skillName = (string)$skillName;
                $linkPath = $mirrorDirectory . '/' . $skillName;
                $primaryEntryPath = $primaryLogicalDirectory . '/' . $skillName;
                $desiredTarget = $this->getRelativePath($mirrorDirectory, $primaryEntryPath);
                $display = "{$mirrorName}/{$skillName}";
                $entryType = $this->getEntryType($linkPath);
                if ($entryType === self::ENTRY_MISSING) {
                    $operations[] = ['kind' => self::OPERATION_LINK, 'path' => $linkPath, 'target' => $desiredTarget, 'display' => "{$display} -> {$desiredTarget}"];
                } elseif ($entryType === self::ENTRY_LINK) {
                    $currentTarget = (string)readlink($linkPath);
                    if ($currentTarget !== $desiredTarget) {
                        $resolvedTarget = $this->resolveLinkTarget($mirrorDirectory, $currentTarget);
                        $pointsToPrimary = $resolvedTarget === $primaryEntryPath || $resolvedTarget === $primaryDirectory . '/' . $skillName;
                        if (!$pointsToPrimary && !$this->isDddVendorPath($resolvedTarget)) {
                            $warnings[] = $this->formatLabel('clash') . "{$display}: a symlink of the app to {$currentTarget} exists; not mirrored";
                            continue;
                        }
                        $operations[] = ['kind' => self::OPERATION_RELINK, 'path' => $linkPath, 'target' => $desiredTarget, 'display' => "{$display} -> {$desiredTarget} (was {$currentTarget})"];
                    }
                } else {
                    $warnings[] = $this->formatLabel('clash') . "{$display}: the app has its own skill of this name; not mirrored";
                    continue;
                }
                $managedEntries[$skillName]['mirrors'][] = $mirrorName;
                $mirrorGitignoreNames[$mirrorDirectory][] = $skillName;
                $gitPaths[] = $linkPath;
            }
            // Mirror cleanup: broken DDD links and links to primary entries that are gone
            foreach ($this->listDirectoryNames($mirrorDirectory) as $entryName) {
                $linkPath = $mirrorDirectory . '/' . $entryName;
                if (isset($managedEntries[$entryName]) || $this->getEntryType($linkPath) !== self::ENTRY_LINK) {
                    continue;
                }
                $currentTarget = (string)readlink($linkPath);
                $resolvedTarget = $this->resolveLinkTarget($mirrorDirectory, $currentTarget);
                $pointsToPrimary = $resolvedTarget === $primaryLogicalDirectory . '/' . $entryName || $resolvedTarget === $primaryDirectory . '/' . $entryName;
                $isBrokenDddLink = !file_exists($linkPath) && $this->isDddVendorPath($resolvedTarget);
                $isFormerMirror = $pointsToPrimary && (isset($removedSkillNames[$entryName]) || isset($previousManifestEntries[$entryName]))
                    && (!file_exists($primaryDirectory . '/' . $entryName) || isset($removedSkillNames[$entryName]));
                if ($isBrokenDddLink || $isFormerMirror) {
                    $operations[] = ['kind' => self::OPERATION_REMOVE, 'path' => $linkPath, 'display' => "{$mirrorName}/{$entryName} (link to removed {$currentTarget})"];
                }
            }
        }

        // Manifest
        $manifestPath = $primaryDirectory . '/' . self::MANIFEST_FILE_NAME;
        $manifestContent = $this->encodeManifest($managedEntries);
        if ((is_file($manifestPath) ? (string)file_get_contents($manifestPath) : null) !== $manifestContent) {
            $operations[] = ['kind' => self::OPERATION_WRITE, 'path' => $manifestPath, 'content' => $manifestContent, 'display' => self::PRIMARY_SKILLS_DIRECTORY . '/' . self::MANIFEST_FILE_NAME];
        }

        // Gitignore blocks
        $primaryGitignoreEntries = ['/' . self::MANIFEST_FILE_NAME];
        foreach (array_keys($managedEntries) as $skillName) {
            $primaryGitignoreEntries[] = '/' . $skillName;
            $gitPaths[] = $primaryDirectory . '/' . $skillName;
        }
        $gitPaths[] = $manifestPath;
        $gitignoreTargets = [$primaryDirectory => $primaryGitignoreEntries];
        foreach ($mirrorGitignoreNames as $mirrorDirectory => $skillNames) {
            sort($skillNames, SORT_STRING);
            $gitignoreTargets[$mirrorDirectory] = array_map(static fn(string $skillName): string => '/' . $skillName, $skillNames);
        }
        foreach ($gitignoreTargets as $directory => $gitignoreEntries) {
            $gitignorePath = $directory . '/' . self::GITIGNORE_FILE_NAME;
            $currentContent = is_file($gitignorePath) ? (string)file_get_contents($gitignorePath) : null;
            $newContent = $this->createGitignoreContent($currentContent, $gitignoreEntries);
            if ($newContent === null) {
                $warnings[] = $this->formatLabel('gitignore') . $this->getDisplayPath($gitignorePath) . ': ' . self::GITIGNORE_BLOCK_START . ' without ' . self::GITIGNORE_BLOCK_END . '; left as is';
            } elseif ($newContent !== ($currentContent ?? '')) {
                $operations[] = ['kind' => self::OPERATION_WRITE, 'path' => $gitignorePath, 'content' => $newContent, 'display' => $this->getDisplayPath($gitignorePath)];
            }
        }

        // Generated links still tracked by git
        $trackedPaths = $this->findTrackedPaths($gitPaths);
        if (count($trackedPaths) > 0) {
            $quotedPaths = implode(' ', array_map([$this, 'quoteShellArgument'], $trackedPaths));
            $warnings[] = $this->formatLabel('tracked') . count($trackedPaths) . ' generated path(s) are still tracked by git; run in '
                . $this->rootDirectory . ": git rm --cached -- {$quotedPaths} (then commit with the updated .gitignore)";
        }

        $packageNames = [];
        foreach ($managedEntries as $managedEntry) {
            if (is_string($managedEntry['package'])) {
                $packageNames[$managedEntry['package']] = true;
            }
        }
        $visibleOperations = array_values(array_filter($operations, static fn(array $operation): bool => $operation['kind'] !== 'mkdir'));
        return [
            'nothingToDo' => false,
            'operations' => $visibleOperations,
            'warnings' => $warnings,
            'managedSkillNames' => array_map('strval', array_keys($managedEntries)),
            'packageNames' => array_keys($packageNames),
        ];
    }

    /**
     * Finds the skills of all DDD packages below the root, in deterministic order (relative skill path, byte order).
     * The first package shipping a name wins; another package with the same name is a clash. The same package
     * installed twice (two Composer roots) is not a clash.
     *
     * @return array{winners: array<string, array>, warnings: string[]}
     */
    protected function discoverSkills(): array
    {
        $candidates = [];
        foreach ($this->findPackages($this->rootDirectory, 0) as $package) {
            $skillsDirectory = $package['directory'] . '/.claude/skills';
            foreach ($this->listDirectoryNames($skillsDirectory) as $skillName) {
                $skillDirectory = $skillsDirectory . '/' . $skillName;
                if (str_starts_with($skillName, '.') || !is_dir($skillDirectory) || !is_file($skillDirectory . '/SKILL.md')) {
                    continue;
                }
                $candidates[] = [
                    'name' => $skillName,
                    'package' => $package['package'],
                    'version' => $package['version'],
                    'directory' => $skillDirectory,
                ];
            }
        }
        usort($candidates, static fn(array $first, array $second): int => strcmp($first['directory'], $second['directory']));
        $winners = [];
        $warnings = [];
        foreach ($candidates as $candidate) {
            $winner = $winners[$candidate['name']] ?? null;
            if ($winner === null) {
                $winners[$candidate['name']] = $candidate;
            } elseif ($winner['package'] !== $candidate['package']) {
                $warnings[] = $this->formatLabel('clash') . "{$candidate['name']}: shipped by {$winner['package']} ("
                    . $this->getRelativePath($this->rootDirectory, $winner['directory']) . ") and {$candidate['package']} ("
                    . $this->getRelativePath($this->rootDirectory, $candidate['directory']) . "); {$winner['package']} kept";
            }
        }
        return ['winners' => $winners, 'warnings' => $warnings];
    }

    /**
     * @return array<int, array{package: string, directory: string, version: ?string}>
     */
    protected function findPackages(string $directory, int $depth): array
    {
        $packages = [];
        $composerScopeDirectory = $directory . '/vendor/mgamadeus';
        if (is_dir($composerScopeDirectory)) {
            $installedVersions = $this->readComposerInstalledVersions($directory . '/vendor/composer/installed.json');
            foreach ($this->listDirectoryNames($composerScopeDirectory) as $packageFolderName) {
                $packageDirectory = $composerScopeDirectory . '/' . $packageFolderName;
                if (!is_dir($packageDirectory)) {
                    continue;
                }
                $packageName = 'mgamadeus/' . $packageFolderName;
                $packages[] = [
                    'package' => $packageName,
                    'directory' => $packageDirectory,
                    'version' => $installedVersions[$packageName] ?? $this->readJsonVersion($packageDirectory . '/composer.json'),
                ];
            }
        }
        $npmScopeDirectory = $directory . '/node_modules/@mgamadeus';
        if (is_dir($npmScopeDirectory)) {
            foreach ($this->listDirectoryNames($npmScopeDirectory) as $packageFolderName) {
                $packageDirectory = $npmScopeDirectory . '/' . $packageFolderName;
                if (!is_dir($packageDirectory)) {
                    continue;
                }
                $packages[] = [
                    'package' => '@mgamadeus/' . $packageFolderName,
                    'directory' => $packageDirectory,
                    'version' => $this->readJsonVersion($packageDirectory . '/package.json'),
                ];
            }
        }
        if ($depth + 1 >= self::MAXIMUM_INSTALL_FOLDER_DEPTH) {
            return $packages;
        }
        foreach ($this->listDirectoryNames($directory) as $childName) {
            $childDirectory = $directory . '/' . $childName;
            if (
                str_starts_with($childName, '.') || $childName === 'vendor' || $childName === 'node_modules'
                || is_link($childDirectory) || !is_dir($childDirectory)
            ) {
                continue;
            }
            $packages = [...$packages, ...$this->findPackages($childDirectory, $depth + 1)];
        }
        return $packages;
    }

    /**
     * @return array<string, string> Version by package name from Composer's installed.json (format 1 and 2)
     */
    protected function readComposerInstalledVersions(string $installedJsonPath): array
    {
        $versions = [];
        $installed = is_file($installedJsonPath) ? json_decode((string)file_get_contents($installedJsonPath), true) : null;
        $installedPackages = is_array($installed) ? ($installed['packages'] ?? $installed) : [];
        foreach (is_array($installedPackages) ? $installedPackages : [] as $installedPackage) {
            if (is_array($installedPackage) && is_string($installedPackage['name'] ?? null) && is_string($installedPackage['version'] ?? null)) {
                $versions[$installedPackage['name']] = $installedPackage['version'];
            }
        }
        return $versions;
    }

    protected function readJsonVersion(string $jsonPath): ?string
    {
        $decoded = is_file($jsonPath) ? json_decode((string)file_get_contents($jsonPath), true) : null;
        return is_array($decoded) && is_string($decoded['version'] ?? null) ? $decoded['version'] : null;
    }

    /**
     * Real location of `<root>/.claude/skills`, also when it does not exist yet (then `.claude` resolved).
     */
    protected function resolvePrimaryDirectory(): string
    {
        $claudeDirectory = $this->rootDirectory . '/.claude';
        $primaryLogicalDirectory = $this->rootDirectory . '/' . self::PRIMARY_SKILLS_DIRECTORY;
        if (is_dir($primaryLogicalDirectory)) {
            return (string)realpath($primaryLogicalDirectory);
        }
        if (is_link($primaryLogicalDirectory) || file_exists($primaryLogicalDirectory)) {
            throw new RuntimeException(self::PRIMARY_SKILLS_DIRECTORY . ' exists but is not a folder (broken symlink?)');
        }
        if (is_dir($claudeDirectory)) {
            return realpath($claudeDirectory) . '/skills';
        }
        if (is_link($claudeDirectory) || file_exists($claudeDirectory)) {
            throw new RuntimeException('.claude exists but is not a folder (broken symlink?)');
        }
        return $primaryLogicalDirectory;
    }

    /**
     * @return array<string, array>|null Entries of the previous manifest by skill name; null when it cannot be read
     */
    protected function readManifestEntries(string $manifestPath): ?array
    {
        if (!is_file($manifestPath)) {
            return [];
        }
        try {
            $manifest = json_decode((string)file_get_contents($manifestPath), true, 512, JSON_THROW_ON_ERROR);
        } catch (JsonException) {
            $manifest = null;
        }
        if (!is_array($manifest) || !is_array($manifest['skills'] ?? null)) {
            return null;
        }
        return $manifest['skills'];
    }

    /**
     * The manifest exactly as both implementations write it: 4-space JSON, sorted names, trailing newline.
     *
     * @param array<string, array> $managedEntries
     */
    protected function encodeManifest(array $managedEntries): string
    {
        $skills = [];
        foreach ($managedEntries as $skillName => $managedEntry) {
            $mirrors = $managedEntry['mirrors'];
            sort($mirrors, SORT_STRING);
            $skills[(string)$skillName] = [
                'package' => $managedEntry['package'],
                'version' => $managedEntry['version'],
                'source' => $managedEntry['source'],
                'target' => $managedEntry['target'],
                'sha256' => $managedEntry['sha256'],
                'mirrors' => $mirrors,
            ];
        }
        $manifest = ['format' => self::MANIFEST_FORMAT, 'skills' => count($skills) > 0 ? $skills : (object)[]];
        return json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR) . "\n";
    }

    /**
     * New content of a .gitignore with the managed block set to $entries (block removed when $entries is empty).
     * Everything outside the block is kept.
     *
     * @param string[] $entries
     * @return string|null null when a start marker has no end marker (the file is left alone)
     */
    protected function createGitignoreContent(?string $currentContent, array $entries): ?string
    {
        $lines = $currentContent === null || $currentContent === '' ? [] : explode("\n", rtrim($currentContent, "\n"));
        $startIndex = array_search(self::GITIGNORE_BLOCK_START, $lines, true);
        $block = count($entries) > 0
            ? [self::GITIGNORE_BLOCK_START, self::GITIGNORE_BLOCK_COMMENT, ...$entries, self::GITIGNORE_BLOCK_END]
            : [];
        if ($startIndex === false) {
            if (count($block) === 0) {
                return $currentContent ?? '';
            }
            if (count($lines) > 0 && $lines[count($lines) - 1] !== '') {
                $lines[] = '';
            }
            return implode("\n", [...$lines, ...$block]) . "\n";
        }
        $endIndex = null;
        for ($index = $startIndex + 1; $index < count($lines); $index++) {
            if ($lines[$index] === self::GITIGNORE_BLOCK_END) {
                $endIndex = $index;
                break;
            }
        }
        if ($endIndex === null) {
            return null;
        }
        $before = array_slice($lines, 0, $startIndex);
        $after = array_slice($lines, $endIndex + 1);
        if (count($block) === 0 && count($before) > 0 && $before[count($before) - 1] === '') {
            array_pop($before);
        }
        $newLines = [...$before, ...$block, ...$after];
        return count($newLines) > 0 ? implode("\n", $newLines) . "\n" : '';
    }

    /**
     * @param string[] $absolutePaths
     * @return string[] Paths (relative to the root) git still tracks; empty without git or outside a work tree
     */
    protected function findTrackedPaths(array $absolutePaths): array
    {
        $relativePaths = [];
        foreach ($absolutePaths as $absolutePath) {
            if (str_starts_with($absolutePath, $this->rootDirectory . '/')) {
                $relativePaths[] = substr($absolutePath, strlen($this->rootDirectory) + 1);
            }
        }
        if (count($relativePaths) === 0 || !function_exists('proc_open')) {
            return [];
        }
        $process = @proc_open(
            ['git', '-C', $this->rootDirectory, 'ls-files', '-z', '--', ...$relativePaths],
            [1 => ['pipe', 'w'], 2 => ['pipe', 'w']],
            $pipes
        );
        if (!is_resource($process)) {
            return [];
        }
        $output = (string)stream_get_contents($pipes[1]);
        stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        if (proc_close($process) !== 0) {
            return [];
        }
        $trackedPaths = array_values(array_filter(explode("\0", $output), static fn(string $path): bool => $path !== ''));
        sort($trackedPaths, SORT_STRING);
        return array_values(array_unique($trackedPaths));
    }

    /**
     * @param array $operations Operations of the plan, in order
     */
    protected function applyOperations(array $operations): void
    {
        $primaryDirectory = $this->resolvePrimaryDirectory();
        if (!is_dir($primaryDirectory) && !mkdir($primaryDirectory, 0777, true) && !is_dir($primaryDirectory)) {
            throw new RuntimeException("cannot create {$primaryDirectory}");
        }
        $orderedKinds = [self::OPERATION_REMOVE, self::OPERATION_RELINK, self::OPERATION_LINK, self::OPERATION_WRITE];
        foreach ($orderedKinds as $kind) {
            foreach ($operations as $operation) {
                if ($operation['kind'] !== $kind) {
                    continue;
                }
                if ($kind === self::OPERATION_REMOVE || $kind === self::OPERATION_RELINK) {
                    if (!unlink($operation['path'])) {
                        throw new RuntimeException("cannot remove {$operation['path']}");
                    }
                }
                if (($kind === self::OPERATION_RELINK || $kind === self::OPERATION_LINK) && !symlink($operation['target'], $operation['path'])) {
                    throw new RuntimeException("cannot create the symlink {$operation['path']}");
                }
                if ($kind === self::OPERATION_WRITE && file_put_contents($operation['path'], $operation['content']) === false) {
                    throw new RuntimeException("cannot write {$operation['path']}");
                }
            }
        }
        clearstatcache(true);
    }

    protected function getEntryType(string $path): string
    {
        if (is_link($path)) {
            return self::ENTRY_LINK;
        }
        if (!file_exists($path)) {
            return self::ENTRY_MISSING;
        }
        return is_dir($path) ? self::ENTRY_DIRECTORY : self::ENTRY_FILE;
    }

    /**
     * @return string[] Entry names of a folder in byte order; empty when it cannot be read
     */
    protected function listDirectoryNames(string $directory): array
    {
        if (!is_dir($directory)) {
            return [];
        }
        $entryNames = @scandir($directory);
        if ($entryNames === false) {
            return [];
        }
        $entryNames = array_values(array_filter($entryNames, static fn(string $entryName): bool => $entryName !== '.' && $entryName !== '..'));
        sort($entryNames, SORT_STRING);
        return $entryNames;
    }

    /**
     * True when a path lies inside a `vendor/mgamadeus/` or `node_modules/@mgamadeus/` folder.
     */
    protected function isDddVendorPath(string $path): bool
    {
        $path .= '/';
        return str_contains($path, '/vendor/mgamadeus/') || str_contains($path, '/node_modules/@mgamadeus/');
    }

    /**
     * Absolute, lexically normalised target of a symlink (no filesystem access, works for broken links).
     */
    protected function resolveLinkTarget(string $linkDirectory, string $target): string
    {
        return $this->normalizePath(str_starts_with($target, '/') ? $target : $linkDirectory . '/' . $target);
    }

    protected function normalizePath(string $absolutePath): string
    {
        $segments = [];
        foreach (explode('/', $absolutePath) as $segment) {
            if ($segment === '' || $segment === '.') {
                continue;
            }
            if ($segment === '..') {
                array_pop($segments);
                continue;
            }
            $segments[] = $segment;
        }
        return '/' . implode('/', $segments);
    }

    /**
     * Relative path from a folder to a path, both absolute.
     */
    protected function getRelativePath(string $fromDirectory, string $toPath): string
    {
        $fromSegments = array_values(array_filter(explode('/', $this->normalizePath($fromDirectory)), 'strlen'));
        $toSegments = array_values(array_filter(explode('/', $this->normalizePath($toPath)), 'strlen'));
        $commonLength = 0;
        while (
            $commonLength < count($fromSegments) && $commonLength < count($toSegments)
            && $fromSegments[$commonLength] === $toSegments[$commonLength]
        ) {
            $commonLength++;
        }
        $relativeSegments = [
            ...array_fill(0, count($fromSegments) - $commonLength, '..'),
            ...array_slice($toSegments, $commonLength),
        ];
        return count($relativeSegments) > 0 ? implode('/', $relativeSegments) : '.';
    }

    protected function getDisplayPath(string $absolutePath): string
    {
        return str_starts_with($absolutePath, $this->rootDirectory . '/')
            ? substr($absolutePath, strlen($this->rootDirectory) + 1)
            : $absolutePath;
    }

    protected function quoteShellArgument(string $argument): string
    {
        return preg_match('#^[A-Za-z0-9._/@+=:-]+$#', $argument) === 1
            ? $argument
            : "'" . str_replace("'", "'\\''", $argument) . "'";
    }

    protected function formatLabel(string $label): string
    {
        return str_pad($label, 13);
    }

    protected function printChange(string $line): void
    {
        if (!$this->quiet) {
            $this->printLine($this->outputStream, $line);
        }
    }

    protected function printInfo(string $line): void
    {
        if (!$this->quiet) {
            $this->printLine($this->outputStream, $line);
        }
    }

    protected function printWarning(string $line): void
    {
        $this->printLine($this->errorStream, $line);
    }

    /**
     * @param resource|null $stream
     */
    protected function printLine(mixed $stream, string $line): void
    {
        $this->printedLines[] = $line;
        if (is_resource($stream)) {
            fwrite($stream, self::OUTPUT_PREFIX . $line . "\n");
        }
    }
}
